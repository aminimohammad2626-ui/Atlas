def S(text):
    return get_display(arabic_reshaper.reshape(text))


def fa_wrap(text, style, width):
    words = text.split()
    lines, cur = [], []
    for w in words:
        cur.append(w)
        if pdfmetrics.stringWidth(S(' '.join(cur)), style.fontName, style.fontSize) > width and len(cur) > 1:
            cur.pop()
            lines.append(' '.join(cur))
            cur = [w]
    if cur:
        lines.append(' '.join(cur))
    return [Paragraph(S(l), style) for l in lines]


class Guide:
    def __init__(self, path):
        self.doc = BaseDocTemplate(path, pagesize=A4,
                                   leftMargin=18 * mm, rightMargin=18 * mm,
                                   topMargin=20 * mm, bottomMargin=18 * mm,
                                   title='Atlas User Guide (FA)', author='Atlas')
        frame = Frame(self.doc.leftMargin, self.doc.bottomMargin,
                      self.doc.width, self.doc.height, id='f')
        self.doc.addPageTemplates([PageTemplate(id='p', frames=[frame], onPage=self.deco)])
        self.width = self.doc.width
        self.story = []

    def deco(self, canv, doc):
        canv.saveState()
        canv.setFillColor(ACCENT)
        canv.rect(0, A4[1] - 8 * mm, A4[0], 8 * mm, stroke=0, fill=1)
        canv.setFont('Vazir', 8)
        canv.setFillColor(MUTED)
        canv.drawRightString(A4[0] - 18 * mm, 12 * mm, S('راهنمای کاربر اطلس — نسخه ۱.۰.۰'))
        canv.drawString(18 * mm, 12 * mm, 'Atlas 1.0.0')
        canv.restoreState()

    def h1(self, num, text):
        self.story.append(Paragraph(S(f'{num}. {text}'), st_h1))
        self.story.append(HRFlowable(width='100%', thickness=0.7, color=ACCENT, spaceAfter=5))

    def h2(self, text):
        self.story.append(Paragraph(S(text), st_h2))

    def p(self, text):
        self.story.extend(fa_wrap(text, st_body, self.width))

    def bullets(self, items):
        for it in items:
            self.story.extend(fa_wrap('•  ' + it, st_bullet, self.width - 14))
        self.story.append(Spacer(1, 3))

    def note(self, text):
        tbl = Table([[Paragraph(S('! ' + text), st_note)]], colWidths=[self.width])
        tbl.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#fef3c7')),
            ('BOX', (0, 0), (-1, -1), 0.7, colors.HexColor('#f59e0b')),
            ('LEFTPADDING', (0, 0), (-1, -1), 8), ('RIGHTPADDING', (0, 0), (-1, -1), 8),
            ('TOPPADDING', (0, 0), (-1, -1), 5), ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        self.story.extend([Spacer(1, 3), tbl, Spacer(1, 5)])

    def table(self, headers, rows, colWidths):
        data = [[Paragraph(S(h), st_cellh) for h in headers]]
        for r in rows:
            data.append([Paragraph(S(c), st_cell) for c in r])
        tbl = Table(data, colWidths=colWidths)
        tbl.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), ACCENT),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f1f5f9')]),
            ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#cbd5e1')),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('LEFTPADDING', (0, 0), (-1, -1), 5), ('RIGHTPADDING', (0, 0), (-1, -1), 5),
            ('TOPPADDING', (0, 0), (-1, -1), 4), ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        self.story.extend([Spacer(1, 3), tbl, Spacer(1, 5)])

    def build(self):
        self.doc.build(self.story)


